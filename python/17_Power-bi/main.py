# DAX = Stand For (Data Analysis Expressions)
# DAX Power BI ki formula language hai, jisse hum data se calculation, analysis aur useful information nikalte hain.

# 1. Ye kya hai?

# DAX ek formula language hai.
# Iski help se hum apne data par questions ke answers nikal sakte hain:

# Total Sales kitni hai?
# Average Sales kitni hai?
# Profit kitna hua?
# Is saal ki sales pichhle saal se kitni zyada hai?
# Delhi mein kitni sales hui?
# Sabse zyada sales kis product ki hai?
# Sales growth kitni % hai?

# 2. DAX kyun hai?

# Socho aapke paas 10 lakh rows ka sales data hai.
# Aap manually calculator se total nahi nikal sakte.
# Aur sirf total bhi nahi chahiye. Aapko questions poochne hain:

# "2026 mein Delhi ki sales kitni thi?"
# "Laptop ki sales kitni thi?"
# "January ki sales February se kitni kam thi?"
# Yahan DAX ka kaam start hota hai.

# DAX ka main purpose:
# Raw Data → Calculation → Meaningful Information

# 3. DAX kaise kaam karta hai?

# Sabse important concept hai
# Data + Formula + Context = Result
# Maan lo:

# Total Sales = SUM(Sales[Amount])
# Power BI dekhega:
# Sales table ki Amount column
# Phir sabhi relevant rows ka SUM karega.
# Agar report mein filter laga diya:
# City = Delhi
# to DAX sirf Delhi ki relevant rows ko consider karega.

# 5. DAX ka use kahan hota hai?

# DAX mainly Power BI mein use hota hai:

# 📊 Business Reports

# Sales Report
# Profit Report
# HR Report
# Finance Report
# Inventory Report
# Marketing Report

# 📈 Analysis

# Total
# Average
# Percentage
# Growth
# Ranking
# Comparison
# Year-over-Year analysis
# Month-over-Month analysis

# 🎯 Dashboard

# Jaise dashboard par:
# Total Sales → ₹50 Crore
# Total Profit → ₹8 Crore
# Profit Margin → 16%
# Sales Growth → +12%
# In numbers ko calculate karne ke liye DAX bahut important hai.

