# -----------------------------------------------------------------------------------
#       Set बनाना
# -----------------------------------------------------------------------------------

# s = {1, 2, 3, 4}

# -----------------------------------------------------------------------------------
#       Empty Set
# -----------------------------------------------------------------------------------

# s = set()      # सही
# d = {}         # यह Dictionary है, Set नहीं
# -----------------------------------------------------------------------------------
#       Set में Element जोड़ना
# -----------------------------------------------------------------------------------
# add() → Set में एक नया element जोड़ता है।

# update() → Set में एक साथ कई elements जोड़ता है।

# remove() → दिए गए element को हटाता है। अगर element मौजूद नहीं है तो KeyError देता है।

# discard() → दिए गए element को हटाता है। अगर element मौजूद नहीं है तो कोई error नहीं देता।

# pop() → Set से कोई एक random element हटाकर return करता है।

# clear() → Set के सभी elements हटा देता है और Set खाली कर देता है।

# copy() → Set की एक नई (shallow) copy बनाता है।

# union() → दो या दो से अधिक Sets के सभी unique elements को मिलाकर नया Set बनाता है।

# intersection() → दो Sets में मौजूद common (समान) elements देता है।

# difference() → पहले Set के वे elements देता है जो दूसरे Set में नहीं हैं।

# symmetric_difference() → दोनों Sets के ऐसे elements देता है जो केवल किसी एक Set में हों, common elements नहीं।

# issubset() → जाँचता है कि एक Set, दूसरे Set का subset है या नहीं। (True/False)

# issuperset() → जाँचता है कि एक Set, दूसरे Set का superset है या नहीं। (True/False)

# isdisjoint() → जाँचता है कि दोनों Sets में कोई common element है या नहीं। अगर common element नहीं है तो True देता है।

