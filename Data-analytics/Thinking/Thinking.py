# 30-minute daily routine
# 10 min: Ek business problem choose karo.
# 10 min: Us problem par 5–10 questions banao.
# 10 min: Socho ki answer nikalne ke liye kaunsa data chahiye.

# Example :- E-commerce Sales Problem
# Business Problem
# Maan lo ek online shopping company ka owner bolta hai:
# “Hamari sales pichhle month ke comparison mein kam ho gayi hain. Humein samajhna hai ki sales kyun kam hui.” 

# Ab Data Analyst ki tarah WHY poochna hai.

# Main 8 questions banaunga:

# Sales kitni % decrease hui?
# Kis month/week se sales decrease hui?
# Kis product ki sales sabse zyada decrease hui?
# Kis city/region mein sales decrease hui?
# Kya total orders kam hue?
# Kya average order value (AOV) kam hui?
# Kya new customers kam aaye?
# Kya kisi product ka stock available nahi tha?

