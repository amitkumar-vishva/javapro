# Data Analytics – Important Concepts
# --------------------------------------------------------
# 1. The Mindset Shift
# --------------------------------------------------------

# Meaning:
# Data Analyst ka kaam sirf data dekhna nahi hai. Humein business problem ko samajhkar data se solution find karna hota hai.

# Think like this:
# Business Problem → Question → Data → Analysis → Insight → Decision

# Example:
# Sales kam ho rahi hai. Sirf sales number dekhne ke bajay:

# Sales kab se kam hui?

# Kis product ki sales kam hui?

# Kis city mein sales kam hui?

# Sales kam hone ka reason kya hai?

# Key Point:

# Don't just analyze data. Solve the business problem.

# --------------------------------------------------------
# 2. Ask “WHY?” Before “WHAT?”
# --------------------------------------------------------

# Meaning:
# Sirf ye mat dekho ki kya hua. Ye samajhne ki koshish karo ki kyun hua.

# Example:

# WHAT? → Sales 20% decrease hui.

# WHY? → Kis wajah se sales decrease hui?

# Possible reasons:

# Orders kam hue

# Product ki demand kam hui

# Price increase hua

# Kisi region mein sales kam hui

# Key Point:

# A good Data Analyst asks “Why?” before jumping to “What?”

# --------------------------------------------------------
# 3. Think in Stories, Not Numbers
# --------------------------------------------------------

# Meaning:
# Numbers ko sirf report nahi karna hai. Numbers se ek story/insight explain karni hai.

# Example:

# ❌ “February sales = ₹8 lakh.”

# ✅ “February mein sales 20% decrease hui, mainly West region aur Product A ki lower sales ke karan.”

# Key Point:

# Numbers tell us WHAT happened; storytelling helps explain WHAT it means.

# --------------------------------------------------------
# 4. Always Question Your Data
# --------------------------------------------------------

# Meaning:
# Data ko blindly trust nahi karna chahiye. Analysis se pehle data ko check aur clean karo.

# Check:

# Missing values

# Duplicate values

# Wrong dates

# Wrong data types

# Outliers

# Incorrect calculations

# Example:
# Agar ek product ki price ₹5000 hai aur data mein ₹50,000 hai, to analysis karne se pehle check karo ki value correct hai ya nahi.

# Key Point:

# Wrong data → Wrong analysis → Wrong decision.

# --------------------------------------------------------
# 5. Is Coding Worth It? + Domain Knowledge
# --------------------------------------------------------
# Coding

# Data Analytics mein coding useful hai, especially:

# SQL → Most important for working with databases

# Python → Useful for advanced analysis, automation and large datasets

# Important Skills

# Excel

# SQL

# Power BI / Tableau

# Statistics

# Python

# Domain Knowledge

# Domain knowledge ka matlab hai jis business/industry mein kaam kar rahe ho usko samajhna.

# Examples:

# Finance → Revenue, Profit, ROI

# Marketing → CTR, Conversion Rate, CAC

# E-commerce → Orders, AOV, Retention

# Key Point:

# Tools tell you HOW to analyze; domain knowledge helps you understand WHAT the numbers mean.

